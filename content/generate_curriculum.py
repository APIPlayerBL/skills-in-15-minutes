def make_tasks(topic):
    title, intro, prompt, correct, distractors = topic
    options = [{"id": "a", "text": correct}] + [{"id": chr(ord('b')+i), "text": d} for i, d in enumerate(distractors)]
    return [{
        "kind": "mcq",
        "prompt": prompt,
        "options": options,
        "answer": "a",
        "weight": 1
    }]

TRACKS = []

def add_track(slug, title, desc, difficulty, minutes, skill_slug, lessons):
    TRACKS.append({
        "slug": slug,
        "title": title,
        "description": desc,
        "difficulty": difficulty,
        "estimated_minutes": minutes,
        "skill": skill_slug,
        "lessons": lessons,
    })

for slug in CORE:
    topics = CORE[slug]
    base_title = BASE_TITLE[slug]
    skill_slug = slug
    # beginner (existing slug)
    lessons = []
    for i, topic in enumerate(topics, 1):
        lessons.append({
            "slug": f"lesson-{i:02}",
            "title": topic[0],
            "minutes": 15,
            "intro": topic[1],
            "tasks": make_tasks(topic),
        })
    add_track(BASE_TRACK_SLUG[slug], base_title, "Базовый курс с практическими заданиями", "beginner", len(lessons) * 15, skill_slug, lessons)

    for level in (2, 3):
        lessons = []
        for i, topic in enumerate(topics, 1):
            lessons.append({
                "slug": f"level{level}-lesson-{i:02}",
                "title": f"Уровень {level} — {topic[0]}",
                "minutes": 15,
                "intro": topic[1],
                "tasks": make_tasks(topic),
            })
        diff = "intermediate" if level == 2 else "advanced"
        track_slug = f"{slug}-level{level}"
        add_track(track_slug, f"{base_title} — уровень {level}", "Повышенная сложность", diff, len(lessons) * 15, skill_slug, lessons)

